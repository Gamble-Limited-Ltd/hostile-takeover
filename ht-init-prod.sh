#!/usr/bin/env bash
# One-time setup for the Hostile Takeover production stack (docker-compose.prod.yml):
#   - writes .env.prod (mode 600) with fresh random secrets, unless it already exists
#   - creates the Ed25519 JWT signing key outside git (default ~/.config/hostile-takeover/keys/, dir 700, file 600)
# Never overwrites an existing file. Safe to re-run.
set -Eeuo pipefail
cd "$(dirname "$0")"

KEYS_DIR="${HT_KEYS_DIR:-$HOME/.config/hostile-takeover/keys}"
KEY_FILE="$KEYS_DIR/jwt-ed25519.pem"

command -v openssl > /dev/null || {
    echo "ht-init-prod: openssl is required" >&2
    exit 1
}

if [ -e .env.prod ]; then
    echo ".env.prod already exists; leaving it alone."
else
    umask 077
    db_password="$(openssl rand -hex 24)"
    api_key="$(openssl rand -hex 32)"
    {
        echo "# Generated by ht-init-prod.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Secrets: never commit."
        echo "POSTGRES_DB=hostile_takeover"
        echo "POSTGRES_USER=hostile_takeover"
        echo "POSTGRES_PASSWORD=$db_password"
        echo "HT_DB_NAME=hostile_takeover"
        echo "HT_DB_USER=hostile_takeover"
        echo "HT_DB_PASSWORD=$db_password"
        echo "API_KEY=$api_key"
    } > .env.prod
    chmod 600 .env.prod
    echo "Wrote .env.prod (mode 600)."
fi

if [ -e "$KEY_FILE" ]; then
    echo "$KEY_FILE already exists; leaving it alone."
else
    umask 077
    mkdir -p "$KEYS_DIR"
    chmod 700 "$KEYS_DIR"
    # Same format as `npm run api:keygen`: an Ed25519 key as a PKCS8 PEM.
    openssl genpkey -algorithm ed25519 -out "$KEY_FILE"
    chmod 600 "$KEY_FILE"
    echo "Wrote the JWT signing key to $KEY_FILE (mode 600). Back it up: losing it signs everyone out."
fi

echo "Next: ./ht-deploy.sh"
